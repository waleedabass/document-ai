import { notFound } from "next/navigation";
import { db } from "@/lib/db";
import { formatMoney, timeAgo } from "@/lib/format";

export const dynamic = "force-dynamic";

export default async function ProposalPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const proposal = await db.proposal.findUnique({ where: { id } });
  if (!proposal) notFound();

  const sections = JSON.parse(proposal.sections) as { heading: string; body: string }[];
  const lineItems = JSON.parse(proposal.lineItems) as { description: string; price: number }[];

  return (
    <div className="flex flex-col gap-6">
      <div className="flex items-start justify-between gap-4 flex-wrap">
        <div>
          <p className="mono text-xs uppercase tracking-wider" style={{ color: "var(--muted)" }}>
            Prepared for {proposal.clientName}
          </p>
          <h1 className="text-2xl font-semibold tracking-tight mt-1">{proposal.projectTitle}</h1>
          <p className="text-sm mt-1" style={{ color: "var(--muted)" }}>
            Generated by {proposal.model} · {timeAgo(proposal.createdAt)}
          </p>
        </div>
        {proposal.pdfPath && (
          <a href={`/api/proposals/${proposal.id}/pdf`} target="_blank" rel="noopener noreferrer" className="btn btn-primary">
            Download PDF ↓
          </a>
        )}
      </div>

      <div className="panel p-5 flex flex-col gap-5">
        {sections.map((s, i) => (
          <div key={i}>
            <h2 className="text-sm font-semibold mb-1">{s.heading}</h2>
            <p className="text-sm" style={{ color: "var(--muted)" }}>{s.body}</p>
          </div>
        ))}
      </div>

      <div className="panel p-5">
        <h2 className="text-sm font-semibold mb-4">Investment</h2>
        <div className="flex flex-col gap-2">
          {lineItems.map((li, i) => (
            <div key={i} className="flex items-center justify-between text-sm">
              <span>{li.description}</span>
              <span className="mono tabular-nums" style={{ color: "var(--muted)" }}>{formatMoney(li.price)}</span>
            </div>
          ))}
          <div className="flex items-center justify-between pt-3 mt-1 border-t font-semibold" style={{ borderColor: "var(--line-soft)" }}>
            <span>Total</span>
            <span className="mono tabular-nums">{formatMoney(proposal.totalPrice)}</span>
          </div>
        </div>
      </div>

      <details className="panel p-5 text-sm">
        <summary className="cursor-pointer font-medium">Original brief</summary>
        <p className="mt-3 whitespace-pre-wrap" style={{ color: "var(--muted)" }}>{proposal.inputBrief}</p>
      </details>
    </div>
  );
}
